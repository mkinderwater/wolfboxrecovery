#define _FILE_OFFSET_BITS 64
#define _POSIX_C_SOURCE 200809L
#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <inttypes.h>
#include <string.h>
#include <limits.h>
#ifdef _WIN32
#define SEEK64 _fseeki64
#else
#include <sys/types.h>
#define SEEK64 fseeko
#endif
#define MAX_NAL (12u*1024u*1024u)
#define UNIT (20ull*1024ull*1024ull)
static uint32_t be32(const unsigned char *p){return (uint32_t)p[0]<<24|(uint32_t)p[1]<<16|(uint32_t)p[2]<<8|p[3];}
static uint64_t be64(const unsigned char *p){return ((uint64_t)be32(p)<<32)|be32(p+4);}
static int readat(FILE *f,uint64_t p,void *buf,size_t n){if(p>INT64_MAX||SEEK64(f,(int64_t)p,SEEK_SET))return 0;return fread(buf,1,n,f)==n;}
static int emit_nal(FILE *out,const unsigned char *p,size_t n){const unsigned char sc[]={0,0,0,1};return fwrite(sc,1,4,out)==4&&fwrite(p,1,n,out)==n;}
/* HEVC samples in hvc1 are length-prefixed NAL arrays. Reject partial/invalid data. */
int wb_hevc_sample(FILE *out,const unsigned char *data,size_t n,unsigned length_bytes){
 if(length_bytes<1||length_bytes>4)return 0;
 size_t at=0;unsigned count=0;
 while(at<n){if(n-at<length_bytes)return 0;uint32_t z=0;for(unsigned j=0;j<length_bytes;j++)z=(z<<8)|data[at++];
  if(z<2||z>n-at||((data[at]>>1)&0x3f)>63)return 0;
  if(!emit_nal(out,data+at,z))return 0;
  at+=z;count++;}
 return count>0;
}
/* Bound all data to the original image. The source is only ever opened rb. */
static int dump_sample(FILE *img,FILE *out,uint64_t pos,uint32_t n,unsigned length_bytes){
 unsigned char *b=malloc(n);if(!b)return 0;int ok=readat(img,pos,b,n)&&wb_hevc_sample(out,b,n,length_bytes);free(b);return ok;
}
static int select_moov(FILE *img,uint64_t pos,unsigned char **mem,size_t *len){
 unsigned char h[16];if(!readat(img,pos,h,8)||memcmp(h+4,"moov",4))return 0;
 uint64_t size=be32(h);if(size==1){if(!readat(img,pos,h,16))return 0;size=be64(h+8);}
 if(size<8||size>128u*1024u*1024u)return 0;
 unsigned char *b=malloc((size_t)size);if(!b)return 0;
 if(!readat(img,pos,b,(size_t)size)){free(b);return 0;}*mem=b;*len=(size_t)size;return 1;
}
/* hvcC record inside the owning moov, using the ISO HEVCDecoderConfigurationRecord structure. */
static int hevc_config(const unsigned char *moov,size_t n,FILE *out,unsigned *ls){
 for(size_t at=4;at+32<n;at++){
  if(memcmp(moov+at,"hvcC",4))continue;
  uint32_t boxsize=be32(moov+at-4);if(boxsize<31||boxsize>n-(at-4))continue;
  const unsigned char *cfg=moov+at+4;size_t avail=boxsize-8;
  if(avail<23||cfg[0]!=1)continue;
  unsigned length_bytes=(cfg[21]&3)+1;unsigned arrays=cfg[22];size_t p=23;
  int wrote=0,seen_vps=0,seen_sps=0,seen_pps=0;
  for(unsigned a=0;a<arrays;a++){
   if(p+3>avail){wrote=0;break;}unsigned type=cfg[p++]&63;unsigned nalcount=((unsigned)cfg[p]<<8)|cfg[p+1];p+=2;
   if(nalcount>128){wrote=0;break;}
   for(unsigned j=0;j<nalcount;j++){
    if(p+2>avail){wrote=0;break;}unsigned sz=((unsigned)cfg[p]<<8)|cfg[p+1];p+=2;
    if(sz<2||sz>avail-p){wrote=0;break;}
    if(type==32||type==33||type==34){if(!emit_nal(out,cfg+p,sz))return 0;wrote++;if(type==32)seen_vps=1;if(type==33)seen_sps=1;if(type==34)seen_pps=1;}
    p+=sz;
   }
   if(p>avail||!wrote)break;
  }
  if(wrote&&seen_vps&&seen_sps&&seen_pps){*ls=length_bytes;return 1;}
 }
 return 0;
}
/* CSV is generated by our own analyzer, but parse strictly and refuse inconsistent fields. */
int wb_export_preview(const char *image,const char *placements,const char *outpath,uint64_t requested_anchor){
 FILE *csv=fopen(placements,"rb");if(!csv)return 2;
 char line[1024];if(!fgets(line,sizeof(line),csv)){fclose(csv);return 2;}
 uint64_t anchor=0,moov=0,base=0;unsigned track=0,first=0,matched=0;char state[80],reason[80];int found=0;
 while(fgets(line,sizeof(line),csv)){
  uint64_t a,m,b;unsigned t,s,k;char st[80],why[80];
  if(sscanf(line,"%"SCNu64",%"SCNu64",%u,%u,%"SCNu64",%u,%79[^,],%79[^\r\n]",&a,&m,&t,&s,&b,&k,st,why)!=8)continue;
  if(a!=requested_anchor)continue;
  if(found++){fclose(csv);return 3;}
  anchor=a;moov=m;track=t;first=s;base=b;matched=k;strcpy(state,st);strcpy(reason,why);
 }
 fclose(csv);
 if(found!=1||strcmp(state,"ALIGNED_UNIQUE_PREFIX")||base%UNIT||matched<4||matched>96){fprintf(stderr,"Unverified or ambiguous prefix. Export refused.\n");return 3;}
 FILE *img=fopen(image,"rb");if(!img)return 2;
 unsigned char *atom=NULL;size_t atom_size=0;
 if(!select_moov(img,moov,&atom,&atom_size)){fclose(img);return 4;}
 char part[4096];if(strlen(outpath)>sizeof(part)-10){free(atom);fclose(img);return 2;}
 snprintf(part,sizeof(part),"%s.part",outpath);FILE *out=fopen(part,"wb");if(!out){free(atom);fclose(img);return 2;}
 unsigned length_bytes=0;int ok=hevc_config(atom,atom_size,out,&length_bytes);free(atom);
 if(!ok){fprintf(stderr,"No complete HEVC VPS/SPS/PPS configuration; refusing export.\n");fclose(out);fclose(img);remove(part);return 4;}
 /* We must not consume a different tbgp or media unit. Frame lengths are checked
  * by the already-generated unique placements, and we extract exactly its prefix. */
 unsigned char h[16];if(!readat(img,anchor,h,16)){ok=0;}uint64_t boxsize=ok?be32(h):0;
 if(ok&&boxsize==1)boxsize=be64(h+8);
 if(!ok||boxsize<8||boxsize>=UNIT||memcmp(h+4,"tbgp",4)){ok=0;}
 uint64_t pos=anchor+boxsize,end=anchor+UNIT;unsigned video=0;
 while(ok&&pos+20<=end&&video<matched){
  unsigned char w[20];if(!readat(img,pos,w,20)){ok=0;break;}
  uint32_t cls=be32(w),n=be32(w+16);
  if(cls>=1&&cls<=3&&n>=1&&n<=MAX_NAL&&n<=end-pos-20){
   if(cls==1){if(!dump_sample(img,out,pos+20,n,length_bytes)){ok=0;break;}video++;}
   pos+=20+(uint64_t)n;continue;
  }
  if(!memcmp(w+4,"free",4)||!memcmp(w+4,"skip",4)){
   uint64_t z=be32(w);if(z==1)z=be64(w+8);if(z<8||z>end-pos){ok=0;break;}pos+=z;continue;
  }
  if(w[0]==0){unsigned char b[4096];size_t amount=(size_t)((end-pos)<sizeof(b)?end-pos:sizeof(b));
   if(!readat(img,pos,b,amount)){ok=0;break;}size_t z=0;while(z<amount&&b[z]==0)z++;if(z){pos+=z;continue;}}
  ok=0;
 }
 if(video!=matched)ok=0;
 if(fclose(out))ok=0;
 fclose(img);
 if(!ok){remove(part);fprintf(stderr,"Incomplete prefix or invalid HEVC sample. Nothing exported.\n");return 5;}
 if(rename(part,outpath)){remove(part);return 6;}
 printf("Exported %u bounded video samples from image anchor %"PRIu64". Track %u first sample %u.\n",video,anchor,track,first);
 printf("This .hevc is a bounded preview, NOT a complete original recording. Use ffmpeg -f hevc -i clip.hevc -c:v copy clip.mp4 to remux.\n");
 return 0;
}
